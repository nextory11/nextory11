const baseline = structuredClone(pack);
const categoryIndex = new Map();

for (const question of pack.questions) {
  const index = categoryIndex.get(question.category) ?? 0;
  const situation = contexts[question.category]?.[index];
  const ending = endings[question.category];
  if (!situation || !ending) throw new Error(`Missing v2 prompt material for ${question.id}`);
  categoryIndex.set(question.category, index + 1);

  question.version = "2.0.0";
  question.bankVersion = "question-pack-v2";
  question.text.ja = `${situation}、${ending}`;
  question.metadata.source = "NEXTORY11 Question Pack v2 — Statistics × Psychology × Emotion";
  question.metadata.reviewStatus = "editorial-v2-candidate";

  for (const option of question.options) {
    const replacement = motiveOverrides[question.category]?.[option.metadata.primaryTrait];
    if (replacement) option.text.ja = replacement;
  }
}

pack.questionSetVersion = "question-pack-v2";

function invariant(condition, message) {
  if (!condition) throw new Error(message);
}

invariant(pack.questions.length === 220, "Question count changed");
invariant(new Set(pack.questions.map((question) => question.id)).size === 220, "Question IDs are not unique");
for (let index = 0; index < pack.questions.length; index += 1) {
  const before = baseline.questions[index];
  const after = pack.questions[index];
  invariant(before.id === after.id, `Question ID changed at ${index}`);
  invariant(before.category === after.category, `Category changed for ${after.id}`);
  invariant(before.metadata.targetTrait === after.metadata.targetTrait, `Target changed for ${after.id}`);
  invariant(before.options.length === after.options.length, `Answer count changed for ${after.id}`);
  for (let optionIndex = 0; optionIndex < before.options.length; optionIndex += 1) {
    const oldOption = before.options[optionIndex];
    const newOption = after.options[optionIndex];
    invariant(oldOption.id === newOption.id, `Answer ID changed for ${after.id}`);
    invariant(JSON.stringify(oldOption.weights) === JSON.stringify(newOption.weights), `Weights changed for ${after.id}/${newOption.id}`);
    invariant(JSON.stringify(oldOption.metadata) === JSON.stringify(newOption.metadata), `Answer metadata changed for ${after.id}/${newOption.id}`);
  }
}

fs.writeFileSync(bankPath, `${JSON.stringify(pack, null, 2)}\n`, "utf8");
console.log(`Built ${pack.questionSetVersion}: ${pack.questions.length} questions, ${pack.questions.length * 4} answers.`);
